// Writes each package's generated test entry, `test/all_test.dart`, and the
// `paths:` block of its `dart_test.yaml`, or checks that both are current.
//
//   dart tool/test_entry.dart            # write both, then format the entries
//   dart tool/test_entry.dart --check    # write nothing; exit 1 when stale
//
// The entry imports every test file under the package's `test/` with a
// library prefix and calls each file's `main` under a group named by its path
// relative to `test/`, carrying the file's library `@Tags`, `@Timeout` and
// `@TestOn` as the group's, so the package compiles and loads once. A file
// whose `main` cannot run beside others is on [kRunApart] with its reason: the
// entry leaves it out, and `paths:` names it after the entry, so a plain
// `dart test` runs it in its own isolate.
//
// `--check` exits 0 when every entry and `paths:` block is current, 1 with
// each finding when one is stale, and 2 when a file carries what an entry
// cannot.
library;

import 'dart:io';

/// The packages that carry a generated entry, in the order the gate runs them.
const kTestEntryPackages = ['bdp', 'grid_core', 'grid', 'grid_workflows'];

const _asyncMain =
    'its main awaits a loopback probe before it declares its tests, and a '
    "group's body may not be async";

/// The test files that run apart, each in its own isolate: by package, then
/// by path relative to `test/`, with the reason the file cannot run beside
/// the others.
const Map<String, Map<String, String>> kRunApart = {
  'grid_core': {
    'control/control_plane_test.dart': _asyncMain,
    'control/dispose_test.dart': _asyncMain,
    'control/stream_test.dart': _asyncMain,
  },
  'grid': {'status_command_test.dart': _asyncMain},
  'grid_workflows': {
    'circuits/land_live_test.dart':
        'its live landings, run unconfined, fail beside the other files and '
        'pass in an isolate of their own',
    'circuits/ratification_live_test.dart':
        'its two live ratifications, run unconfined, fail beside the other '
        'files and pass in an isolate of their own',
  },
};

/// The entry's path, relative to the package.
const _entry = 'test/all_test.dart';

const _rerun = '; run dart tool/test_entry.dart from the repository root';

/// A test file carries what an entry cannot: [path] names it, relative to the
/// package, and [reason] says why.
class TestEntryError implements Exception {
  /// An error for the file at [path], for [reason].
  TestEntryError(this.path, this.reason);

  /// The offending file, relative to the package.
  final String path;

  /// Why the entry cannot carry it.
  final String reason;

  @override
  String toString() => '$path: $reason';
}

/// The entry [package]'s `test/all_test.dart` should hold, with [runApart]
/// left out.
///
/// Throws a [TestEntryError] for a file the entry cannot carry, a prefix two
/// files share, or a [runApart] path that names no file.
String renderEntry(Directory package, Map<String, String> runApart) {
  final members = _members(package, runApart);
  final declared = _declaredTags(package);
  final byPrefix = <String, String>{};
  final calls = <_Member>[];
  for (final path in members) {
    final prefix = _prefix(path);
    if (byPrefix[prefix] case final other?) {
      throw TestEntryError(
        'test/$path',
        'shares the library prefix $prefix with test/$other',
      );
    }
    byPrefix[prefix] = path;
    calls.add(_member(package, path, prefix, declared));
  }
  final apart = runApart.keys.toList()..sort();
  return [
    '// Generated by tool/test_entry.dart: do not edit. Regenerate it with',
    '// `dart tool/test_entry.dart` from the repository root.',
    '//',
    "// It calls every test file's main under a group named by the file's path,",
    '// so the package compiles and loads once.',
    if (apart.isEmpty)
      '// No file runs apart.'
    else ...[
      "// These files run apart, each in its own isolate, from dart_test.yaml's",
      '// paths:',
      for (final path in apart) ..._comment('- test/$path: ${runApart[path]}.'),
    ],
    'library;',
    '',
    "import 'package:test/test.dart';",
    '',
    for (final call in calls) "import '${call.path}' as ${call.prefix};",
    '',
    'void main() {',
    for (final call in calls) '  ${call.group}',
    '}',
    '',
  ].join('\n');
}

/// [package]'s `dart_test.yaml` with its `paths:` block replaced by the
/// rendered one, every other byte kept, or the block and a blank line at its
/// head when it has none.
String renderTestConfig(Directory package, Map<String, String> runApart) {
  final file = File('${package.path}/dart_test.yaml');
  final text = file.existsSync() ? file.readAsStringSync() : '';
  final block = [
    '# The suites a plain `dart test` runs: the generated test/all_test.dart,',
    '# then each file run apart in its own isolate. tool/test_entry.dart writes',
    '# this block; do not edit it.',
    'paths:',
    '  - $_entry',
    for (final path in runApart.keys.toList()..sort()) '  - test/$path',
  ];
  final lines = text.split('\n');
  final at = lines.indexOf('paths:');
  if (at < 0) return [...block, '', text].join('\n');
  var start = at;
  while (start > 0 && lines[start - 1].startsWith('#')) {
    start--;
  }
  var end = at + 1;
  while (end < lines.length && lines[end].startsWith('  - ')) {
    end++;
  }
  return [
    ...lines.sublist(0, start),
    ...block,
    ...lines.sublist(end),
  ].join('\n');
}

/// What is stale in [package]'s entry and `paths:` block, each finding
/// telling you to run the tool; empty when both are current.
///
/// Throws a [TestEntryError] as [renderEntry] does.
List<String> staleness(Directory package, Map<String, String> runApart) {
  final rendered = renderEntry(package, runApart);
  final members = _members(package, runApart).toSet();
  final entry = File('${package.path}/$_entry');
  final onDisk = entry.existsSync() ? entry.readAsStringSync() : '';
  final called = {
    for (final match in RegExp(r"import '([^']+)'\s+as").allMatches(onDisk))
      match[1]!,
  };
  final config = File('${package.path}/dart_test.yaml');
  return [
    for (final path in members)
      if (!called.contains(path)) 'test/$path is not called by $_entry$_rerun',
    for (final path in called.toList()..sort())
      if (!members.contains(path))
        '$_entry calls test/$path, which is absent$_rerun',
    if (_normalized(onDisk) != _normalized(rendered))
      '$_entry differs from what tool/test_entry.dart renders$_rerun',
    if (!config.existsSync() ||
        config.readAsStringSync() != renderTestConfig(package, runApart))
      "dart_test.yaml's paths block differs from what tool/test_entry.dart "
          'renders$_rerun',
  ];
}

/// Every file the tool writes under [repository], by its path: each of
/// [packages]' entry and `dart_test.yaml`, rendered with its [runApart] list.
///
/// Renders them all before answering, so a [TestEntryError] in any package
/// throws before the caller writes one file.
Map<String, String> renderPackages(
  Directory repository, {
  List<String> packages = kTestEntryPackages,
  Map<String, Map<String, String>> runApart = kRunApart,
}) => {
  for (final name in packages) ...{
    '${repository.path}/packages/$name/$_entry': renderEntry(
      Directory('${repository.path}/packages/$name'),
      runApart[name] ?? const {},
    ),
    '${repository.path}/packages/$name/dart_test.yaml': renderTestConfig(
      Directory('${repository.path}/packages/$name'),
      runApart[name] ?? const {},
    ),
  },
};

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  if (args.any((arg) => arg != '--check')) {
    stderr.writeln('usage: dart tool/test_entry.dart [--check]');
    exitCode = 64;
    return;
  }
  final repository = File.fromUri(Platform.script).parent.parent;
  Directory package(String name) =>
      Directory('${repository.path}/packages/$name');
  try {
    if (check) {
      final findings = [
        for (final name in kTestEntryPackages)
          for (final finding in staleness(
            package(name),
            kRunApart[name] ?? const {},
          ))
            'packages/$name/$finding',
      ];
      if (findings.isNotEmpty) {
        findings.forEach(stderr.writeln);
        exitCode = 1;
        return;
      }
      stdout.writeln(
        'test entries are current: ${kTestEntryPackages.join(', ')}',
      );
      return;
    }
    for (final MapEntry(key: path, value: text) in renderPackages(
      repository,
    ).entries) {
      File(path).writeAsStringSync(text);
    }
  } on TestEntryError catch (error) {
    stderr.writeln(error);
    exitCode = 2;
    return;
  }
  final format = await Process.run('dart', [
    'format',
    for (final name in kTestEntryPackages) '${package(name).path}/$_entry',
  ]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
  exitCode = format.exitCode;
}

/// One file the entry calls: its path relative to `test/`, its library
/// prefix and the `group` call that runs it.
typedef _Member = ({String path, String prefix, String group});

/// Every `_test.dart` file under [package]'s `test/` but the entry and
/// [runApart], relative to `test/` and sorted.
List<String> _members(Directory package, Map<String, String> runApart) {
  final root = Directory('${package.path}/test');
  final all = <String>{
    if (root.existsSync())
      for (final file in root.listSync(recursive: true).whereType<File>())
        if (file.path.endsWith('_test.dart'))
          file.path
              .substring(root.path.length + 1)
              .replaceAll(Platform.pathSeparator, '/'),
  };
  for (final path in runApart.keys) {
    if (!all.contains(path)) {
      throw TestEntryError('test/$path', 'is on the run-apart list but absent');
    }
  }
  return [
    for (final path in all)
      if (path != 'all_test.dart' && !runApart.containsKey(path)) path,
  ]..sort();
}

/// [path] without `.dart`, every character outside `[a-z0-9_]` a `_`.
String _prefix(String path) => path
    .substring(0, path.length - '.dart'.length)
    .replaceAll(RegExp('[^a-z0-9_]'), '_');

/// The file at [path] under [package]'s `test/`, read for the library
/// annotations its group carries.
_Member _member(
  Directory package,
  String path,
  String prefix,
  Set<String> declared,
) {
  final named = 'test/$path';
  final source = File('${package.path}/$named').readAsStringSync();
  if (RegExp(r'^Future<void> main\(', multiLine: true).hasMatch(source)) {
    throw TestEntryError(
      named,
      "its main is async, and a group's body may not be; put it on the "
      'run-apart list in tool/test_entry.dart',
    );
  }
  final lines = source.split('\n');
  var end = lines.indexWhere((line) => line.startsWith(RegExp(r'library\b')));
  if (end < 0) {
    end = lines.indexWhere((line) => line.startsWith(RegExp(r'import\b')));
  }
  final arguments = <String>[];
  for (final line in lines.take(end < 0 ? 0 : end)) {
    final trimmed = line.trim();
    if (!trimmed.startsWith('@')) continue;
    if ('('.allMatches(trimmed).length != ')'.allMatches(trimmed).length) {
      throw TestEntryError(
        named,
        'its annotation $trimmed spans lines, which an entry cannot read; '
        'put it on the run-apart list in tool/test_entry.dart',
      );
    }
    if (RegExp(r'^@Tags\(\[(.*)\]\)$').firstMatch(trimmed) case final match?) {
      final tags = <String>[];
      for (final item in match[1]!.split(',')) {
        if (item.trim().isEmpty) continue;
        final literal = RegExp(
          r'''^\s*(?:'([\w-]+)'|"([\w-]+)")\s*$''',
        ).firstMatch(item);
        if (literal == null) {
          throw TestEntryError(
            named,
            'its annotation $trimmed carries ${item.trim()}, which is no '
            'quoted tag an entry can read; put it on the run-apart list in '
            'tool/test_entry.dart',
          );
        }
        tags.add(literal[1] ?? literal[2]!);
      }
      for (final tag in tags) {
        if (!declared.contains(tag)) {
          throw TestEntryError(
            named,
            "carries the tag $tag, which dart_test.yaml's tags: does not "
            'declare',
          );
        }
      }
      arguments.add('tags: [${tags.map((tag) => "'$tag'").join(', ')}]');
    } else if (RegExp(r'^@Timeout\.factor\((.*)\)$').firstMatch(trimmed)
        case final match?) {
      arguments.add('timeout: Timeout.factor(${match[1]})');
    } else if (RegExp(r'^@Timeout\((.*)\)$').firstMatch(trimmed)
        case final match?) {
      arguments.add('timeout: Timeout(${match[1]})');
    } else if (RegExp(r"^@TestOn\('([^']*)'\)$").firstMatch(trimmed)
        case final match?) {
      arguments.add("testOn: '${match[1]}'");
    } else {
      throw TestEntryError(
        named,
        'its library carries $trimmed, which an entry cannot carry; put it '
        'on the run-apart list in tool/test_entry.dart',
      );
    }
  }
  arguments.sort((a, b) => _order(a).compareTo(_order(b)));
  return (
    path: path,
    prefix: prefix,
    group:
        "group('$path', $prefix.main${[for (final argument in arguments) ', $argument'].join()});",
  );
}

/// Where a group argument sorts: `tags:`, `timeout:`, then `testOn:`.
int _order(String argument) => switch (argument.split(':').first) {
  'tags' => 0,
  'timeout' => 1,
  _ => 2,
};

/// The tags [package]'s `dart_test.yaml` declares: the two-space-indented
/// keys under its top-level `tags:`.
Set<String> _declaredTags(Directory package) {
  final file = File('${package.path}/dart_test.yaml');
  if (!file.existsSync()) return const {};
  final lines = file.readAsLinesSync();
  final at = lines.indexOf('tags:');
  if (at < 0) return const {};
  final declared = <String>{};
  for (final line in lines.skip(at + 1)) {
    if (line.isNotEmpty && !line.startsWith(' ') && !line.startsWith('#')) {
      break;
    }
    if (RegExp(r'^  ([\w-]+):').firstMatch(line) case final match?) {
      declared.add(match[1]!);
    }
  }
  return declared;
}

/// [text] as `//` lines of at most 80 columns, a line after the first
/// indented under a leading `- `.
List<String> _comment(String text) {
  final lines = <String>[];
  var line = '//';
  for (final word in text.split(' ')) {
    if (line.length + 1 + word.length > 80 && line.trim() != '//') {
      lines.add(line);
      line = '//  ';
    }
    line = '$line $word';
  }
  return [...lines, line];
}

/// [source] with every whitespace run and every `,` before `)` or `]`
/// removed, so a formatter's layout never reads as stale.
String _normalized(String source) =>
    source.replaceAll(RegExp(r'\s+'), '').replaceAll(RegExp(r',(?=[)\]])'), '');
